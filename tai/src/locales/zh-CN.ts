type Dict = Record<string, any>

const dictionaries: Record<AppLocale, Dict> = {
  'zh-CN': messages as unknown as Dict,
  'en-US': enUS as unknown as Dict,
}

const LOCALE_STORAGE_KEY = 'tire.locale'
export type AppLocale = 'zh-CN' | 'en-US'

function resolveInitialLocale(): AppLocale {
  try {
    const saved = uni.getStorageSync(LOCALE_STORAGE_KEY)
    if (saved === 'zh-CN' || saved === 'en-US') return saved
    const systemLocale = String(uni.getLocale?.() || '').toLowerCase()
    if (systemLocale.startsWith('en')) return 'en-US'
  } catch (error) {
    // 非 uni 运行环境时回落中文
  }
  return 'zh-CN'
}

let currentLocale: AppLocale = resolveInitialLocale()

export function getLocale(): AppLocale {
  return currentLocale
}

/** 切换语言（持久化到本地存储，供后续设置页或按系统语言切换） */
export function setLocale(locale: AppLocale): void {
  if (!dictionaries[locale]) return
  currentLocale = locale
  try {
    uni.setStorageSync(LOCALE_STORAGE_KEY, locale)
  } catch (error) {
    // 忽略存储失败
  }
}

function readPath(dict: Dict, path: string): any {
  return path.split('.').reduce<any>((acc, key) => (acc ? acc[key] : undefined), dict)
}

/** 取文案，支持 {key} 占位符替换；当前语言缺词条时回落中文 */
export function t(path: string, params?: Record<string, string | number>): string {
  const value = readPath(dictionaries[currentLocale], path)
  const fallbackValue = readPath(dictionaries['zh-CN'], path)
  const current = typeof value === 'string' ? value : typeof fallbackValue === 'string' ? fallbackValue : path
  let text = current
  if (params) {
    Object.keys(params).forEach((key) => {
      text = text.replace(new RegExp(`\\{${key}\\}`, 'g'), String(params[key]))
    })
  }
  return text
}

/** 订单状态文案：到店单与上门单的 accepted 展示不同 */
export function statusText(status: string, serviceType?: string): string {
  if (status === 'accepted') {
    return serviceType === 'pickup' ? t('status.accepted_pickup') : t('status.accepted_store')
  }
  return t(`status.${status}`)
}
